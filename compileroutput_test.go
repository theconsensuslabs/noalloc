// compilerOutput is what go build prints, with -m and -S for every package of
// the module in dir, building pattern there.
func compilerOutput(t *testing.T, dir, pattern string) []byte {
	t.Helper()
	list := exec.Command("go", "list", "-m")
	list.Dir = dir
	mod, err := list.Output()
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("go", "build", "-gcflags="+strings.TrimSpace(string(mod))+"/...=-m -S", "-o", os.DevNull, pattern)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("%v: %s", err, out)
	}
	return out
}

func goEnv(t *testing.T) (goroot, gomodcache string) {
	t.Helper()
	out, err := exec.Command("go", "env", "GOROOT", "GOMODCACHE").Output()
	if err != nil {
		t.Fatal(err)
	}
	f := strings.Fields(string(out))
	return f[0], f[1]
}

// TestTheCompilerReportMatchesTheLineReader holds compilerEscapes to a reader
// that converts every line and tests every pattern on it, on the compiler's
// output for this module and each module under testdata, and on output with
// each kind of line in it. The two agree on every escape, note, inline,
// zero-copy conversion, and assembly record, in order.
func TestTheCompilerReportMatchesTheLineReader(t *testing.T) {
	goroot, gomodcache := goEnv(t)
	inputs := []struct {
		name, dir string
		out       func(t *testing.T, dir string) []byte
	}{
		{name: "edge cases", dir: "testdata/fixture", out: func(*testing.T, string) []byte { return []byte(edgeOutput) }},
		{name: "this module", dir: ".", out: func(t *testing.T, dir string) []byte { return compilerOutput(t, dir, "./...") }},
	}
	mods, err := filepath.Glob("testdata/*/go.mod")
	if err != nil {
		t.Fatal(err)
	}
	for _, m := range mods {
		inputs = append(inputs, struct {
			name, dir string
			out       func(t *testing.T, dir string) []byte
		}{name: filepath.Dir(m), dir: filepath.Dir(m), out: func(t *testing.T, dir string) []byte { return compilerOutput(t, dir, "./...") }})
	}
	for _, in := range inputs {
		t.Run(in.name, func(t *testing.T) {
			dir, err := filepath.Abs(in.dir)
			if err != nil {
				t.Fatal(err)
			}
			out := in.out(t, dir)
			got, gotRecords := readReplayed(t, dir, out, goroot, gomodcache)
			want, wantRecords := lineReader(out, func(f string) string { return reportedFile(f, dir, []string{goroot, gomodcache, dir}) })
			if len(want.notes) == 0 || len(wantRecords) == 0 {
				t.Fatalf("control: the line reader found %d notes and %d assembly records", len(want.notes), len(wantRecords))
			}
			for _, c := range []struct {
				what      string
				got, want []escape
			}{{"escapes", got.escapes, want.escapes}, {"notes", got.notes, want.notes},
				{"inlines", got.inlines, want.inlines}, {"zero-copy conversions", got.zeroCopies, want.zeroCopies}} {
				if !slices.Equal(c.got, c.want) {
					t.Errorf("%s: got %d, want %d\n got: %v\nwant: %v", c.what, len(c.got), len(c.want), c.got, c.want)
				}
			}
			if !slices.Equal(gotRecords, wantRecords) {
				t.Errorf("assembly records: got %d, want %d\n got: %q\nwant: %q", len(gotRecords), len(wantRecords), gotRecords, wantRecords)
			}
			t.Logf("%d lines: %d escapes, %d notes, %d inlines, %d assembly records",
				strings.Count(string(out), "\n"), len(got.escapes), len(got.notes), len(got.inlines), len(gotRecords))
		})
	}
}

// fillerOutput is edgeOutput with n copies of each line noalloc reads past: an
// autogenerated wrapper's instruction before its first positioned one, a
// function's later instruction that calls nothing in the runtime, and hex and
// relocation lines.
func fillerOutput(n int) []byte {
	var b strings.Builder
	b.WriteString("q.(*T).M STEXT dupok size=80 args=0x8 locals=0x8 funcid=0x16 align=0x0\n")
	for i := range n {
		fmt.Fprintf(&b, "\t0x%04x %05d (<autogenerated>:1)\tMOVD\t8(R0), R1\n", i, i)
	}
	b.WriteString("q.h STEXT size=96 args=0x8 locals=0x18 funcid=0x0 align=0x0\n")
	b.WriteString("\t0x0000 00000 (/x/q.go:2)\tTEXT\tq.h(SB), ABIInternal, $32-8\n")
	for i := range n {
		fmt.Fprintf(&b, "\t0x%04x %05d (/x/q.go:%d)\tCALL\tq.k(SB)\n", i, i, 3+i)
		fmt.Fprintf(&b, "\t0x%04x 00 00 00 94 00 00 00 94 00 00 00 94 00 00 00 94  ................\n", i*16)
		fmt.Fprintf(&b, "\trel %d+4 t=R_CALLARM64 q.k+0\n", i*4)
	}
	b.WriteString(edgeOutput)
	return []byte(b.String())
}

// TestTheCompilerReportAllocatesForWhatItKeeps holds compilerEscapes to the
// same count of allocations at 1x, 4x, and 16x the lines of assembly it reads
// past, so what it costs to read go build's output grows with what it finds
// and not with the size of the listing. The control is the line reader, which
// the count has to catch.
func TestTheCompilerReportAllocatesForWhatItKeeps(t *testing.T) {
	goroot, gomodcache := goEnv(t)
	dir, err := filepath.Abs("testdata/fixture")
	if err != nil {
		t.Fatal(err)
	}
	const base = 2000
	const slack = 500
	readers := []struct {
		name  string
		grows bool
		read  func(t *testing.T, out []byte) (escapes int)
	}{
		{name: "compilerEscapes", read: func(t *testing.T, out []byte) int {
			env := replayGo(t, out, goroot, gomodcache)
			cfg := Config{Dir: dir, Patterns: []string{"."}, Module: "example.com/p"}
			var r compilerReport
			allocs := countAllocs(func() {
				if r, err = compilerEscapes(cfg, env, nil); err != nil {
					t.Fatal(err)
				}
			})
			r.asm.close()
			t.Logf("%d bytes: %d allocations", len(out), allocs)
			return allocs
		}},
		{name: "control: the line reader", grows: true, read: func(t *testing.T, out []byte) int {
			return countAllocs(func() { lineReader(out, func(f string) string { return f }) })
		}},
	}
	for _, r := range readers {
		t.Run(r.name, func(t *testing.T) {
			var allocs [3]int
			for i, scale := range []int{1, 4, 16} {
				allocs[i] = r.read(t, fillerOutput(base*scale))
			}
			if grew := allocs[2] > allocs[0]+slack; grew != r.grows {
				t.Errorf("allocations at 1x, 4x, and 16x: %v, growing past %d: %v, want %v", allocs, slack, grew, r.grows)
			}
		})
	}
}

func countAllocs(f func()) int {
	var before, after runtime.MemStats
	runtime.ReadMemStats(&before)
	f()
	runtime.ReadMemStats(&after)
	return int(after.Mallocs - before.Mallocs)
}
