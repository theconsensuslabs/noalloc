// replayGo puts first on the test's PATH a go command that answers "go env" with goroot and
// gomodcache and any build with the bytes of out, and returns the environment
// that runs it.
func replayGo(t *testing.T, out []byte, goroot, gomodcache string) []string {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("the replayed go command is a shell script")
	}
	dir := t.TempDir()
	file := filepath.Join(dir, "output")
	if err := os.WriteFile(file, out, 0o644); err != nil {
		t.Fatal(err)
	}
	script := fmt.Sprintf("#!/bin/sh\nif [ \"$1\" = env ]; then printf '%%s\\n%%s\\n' %q %q; exit 0; fi\ncat %q\n", goroot, gomodcache, file)
	if err := os.WriteFile(filepath.Join(dir, "go"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	// exec.Command finds go on the test's own PATH.
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return os.Environ()
}

// readReplayed runs compilerEscapes on out, the output of a go build run in
// dir, and returns what it read with the assembly's records as lines.
func readReplayed(t *testing.T, dir string, out []byte, goroot, gomodcache string) (compilerReport, []string) {
	t.Helper()
	cfg := Config{Dir: dir, Patterns: []string{"."}, Module: "example.com/p"}
	r, err := compilerEscapes(cfg, replayGo(t, out, goroot, gomodcache), nil)
	if err != nil {
		t.Fatal(err)
	}
	defer r.asm.close()
	var records []string
	if err := r.asm.spill.each(func(f []string) { records = append(records, strings.Join(f, "\t")) }); err != nil {
		t.Fatal(err)
	}
	return r, records
}

// lineReader reads the compiler's output as a string a line, testing every
// pattern on every line, as a reference for compilerEscapes to agree with.
func lineReader(out []byte, file func(string) string) (r compilerReport, records []string) {
	var symbol string
	started := false
	inlined := map[escape]int{}
	var found []escape
	for _, text := range strings.Split(strings.TrimSuffix(string(out), "\n"), "\n") {
		if text != "" {
			if text[0] != '\t' && text[0] != ' ' {
				if i := strings.Index(text, " STEXT"); i > 0 {
					symbol, started = text[:i], false
				}
			} else {
				if m := asmPosition.FindStringSubmatch(text); !started && m != nil {
					started = true
					records = append(records, strings.Join([]string{symbol, m[1], m[2], ""}, "\t"))
				}
				if m := asmCall.FindStringSubmatch(text); m != nil {
					records = append(records, strings.Join([]string{symbol, m[1], m[2], m[3]}, "\t"))
				}
			}
		}
		m := diagLine.FindStringSubmatch(text)
		if m == nil {
			continue
		}
		line, _ := strconv.Atoi(m[2])
		col, _ := strconv.Atoi(m[3])
		at, msg := escape{file: file(m[1]), line: line, col: col}, m[4]
		if !strings.HasPrefix(msg, "inlining call to ") && !strings.HasPrefix(msg, "can inline ") {
			r.notes = append(r.notes, at)
		}
		switch {
		case strings.HasPrefix(msg, "inlining call to "):
			if inlined[at] == 0 {
				r.inlines = append(r.inlines, at)
			}
			inlined[at]++
		case msg == "zero-copy string->[]byte conversion":
			r.zeroCopies = append(r.zeroCopies, at)
		case msg == "append escapes to heap":
		case strings.HasPrefix(msg, "moved to heap: "), strings.HasSuffix(msg, " escapes to heap"):
			at.msg = foldShapes(msg)
			found = append(found, at)
		}
	}
	seen, reports := map[escape]bool{}, map[escape]int{}
	for _, e := range found {
		n := inlined[escape{file: e.file, line: e.line, col: e.col}]
		if e.inlined = n > 0; e.inlined {
			e.nth = reports[e] / n
			reports[e]++
		}
		if !seen[e] {
			seen[e] = true
			r.escapes = append(r.escapes, e)
		}
	}
	return r, records
}

