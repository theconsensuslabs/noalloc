// runtimePath is the package generated code calls, imported as nojson.
const runtimePath = "github.com/theconsensuslabs/noalloc/encoding/json"

// Generate returns the source of out, a file of dir's package, holding the
// methods for the types named in write and read.
func Generate(dir, out string, write, read []string) ([]byte, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports | packages.NeedDeps, Dir: abs}
	// The file being written is read as an empty file of the package, so
	// methods it held before are not taken for the package's own.
	outPath := filepath.Join(abs, out)
	if old, err := os.ReadFile(outPath); err == nil {
		if m := regexp.MustCompile(`(?m)^package \w+`).Find(old); m != nil {
			cfg.Overlay = map[string][]byte{outPath: append(m, '\n')}
		}
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 {
		return nil, fmt.Errorf("%s holds %d packages", dir, len(pkgs))
	}
	// A package mid-change, calling methods this run is about to write, still
	// has the types the methods are written from; compiling the output checks
	// the rest.
	for _, e := range pkgs[0].Errors {
		fmt.Fprintln(os.Stderr, "jsongen: warning:", e)
	}
	if pkgs[0].Types == nil {
		return nil, fmt.Errorf("%s did not type-check", dir)
	}
	g := &gen{pkg: pkgs[0].Types, imports: map[string]string{}, writeDone: map[*types.Named]bool{}, readDone: map[*types.Named]bool{}}
	for _, name := range write {
		if n := g.lookup(name); n != nil {
			g.needWrite(n)
		}
	}
	for _, name := range read {
		if n := g.lookup(name); n != nil {
			g.needRead(n)
		}
	}
	var body bytes.Buffer
	for len(g.writeQueue)+len(g.readQueue) > 0 {
		if len(g.writeQueue) > 0 {
			n := g.writeQueue[0]
			g.writeQueue = g.writeQueue[1:]
			g.writeMethod(n)
		} else {
			n := g.readQueue[0]
			g.readQueue = g.readQueue[1:]
			g.readMethod(n)
		}
		body.Write(g.b.Bytes())
		g.b.Reset()
	}
	if len(g.errs) > 0 {
		return nil, errors.New(strings.Join(g.errs, "\n"))
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by jsongen; DO NOT EDIT.\n\npackage %s\n\nimport (\n", g.pkg.Name())
	fmt.Fprintf(&src, "\tnojson %q\n", runtimePath)
	paths := make([]string, 0, len(g.imports))
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&src, "\t%s %q\n", g.imports[p], p)
	}
	src.WriteString(")\n")
	src.Write(body.Bytes())
	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return src.Bytes(), fmt.Errorf("formatting the output: %w", err)
	}
	return formatted, nil
}

type gen struct {
	pkg                   *types.Package
	imports               map[string]string
	writeDone, readDone   map[*types.Named]bool
	writeQueue, readQueue []*types.Named
	errs                  []string
	b                     bytes.Buffer
	tmp                   int
	// raw is constant output not yet written, which raw writes run together
	// into one w.Raw.
	raw string
}

func (g *gen) p(format string, args ...any) {
	if g.raw != "" {
		fmt.Fprintf(&g.b, "w.Raw(%q)\n", g.raw)
		g.raw = ""
	}
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

// writeRaw writes code that writes s as it is.
func (g *gen) writeRaw(s string) { g.raw += s }

func (g *gen) fail(format string, args ...any) {
	msg := fmt.Sprintf(format, args...)
	if !slices.Contains(g.errs, msg) {
		g.errs = append(g.errs, msg)
	}
}

// v is a fresh variable name.
func (g *gen) v(base string) string {
	g.tmp++
	return fmt.Sprintf("%s%d", base, g.tmp)
}

func (g *gen) lookup(name string) *types.Named {
	obj := g.pkg.Scope().Lookup(name)
	tn, ok := obj.(*types.TypeName)
	if !ok {
		g.fail("%s: no type %s", g.pkg.Path(), name)
		return nil
	}
	n, ok := types.Unalias(tn.Type()).(*types.Named)
	if !ok || n.Obj().Pkg() != g.pkg {
		g.fail("%s is not a type defined in %s", name, g.pkg.Path())
		return nil
	}
	return n
}

// typ is t as generated code writes it.
func (g *gen) typ(t types.Type) string {
	return types.TypeString(t, func(p *types.Package) string {
		if p == g.pkg {
			return ""
		}
		return g.importName(p.Path(), p.Name())
	})
}

func (g *gen) importName(path, name string) string {
	if n, ok := g.imports[path]; ok {
		return n
	}
	used := name == "nojson"
	for _, n := range g.imports {
		used = used || n == name
	}
	if used {
		name = fmt.Sprintf("%s%d", name, len(g.imports))
	}
	g.imports[path] = name
	return name
}

func (g *gen) needWrite(n *types.Named) {
	if !g.writeDone[n] {
		g.writeDone[n] = true
		g.writeQueue = append(g.writeQueue, n)
	}
}

func (g *gen) needRead(n *types.Named) {
	if !g.readDone[n] {
		g.readDone[n] = true
		g.readQueue = append(g.readQueue, n)
	}
}

// has reports whether a value of t, addressable, has the exported method
// name.
func has(t types.Type, name string) bool {
	for _, tt := range []types.Type{t, types.NewPointer(t)} {
		if types.NewMethodSet(tt).Lookup(nil, name) != nil {
			return true
		}
	}
	return false
}

// isByte reports whether t's kind is uint8, which encoding/json decodes a
// slice of from base64.
func isByte(t types.Type) bool {
	b, ok := t.Underlying().(*types.Basic)
	return ok && b.Kind() == types.Uint8
}

// base64Slice reports whether encoding/json writes a slice of elem as
// base64: elem is a byte with no method that writes it otherwise.
func base64Slice(elem types.Type) bool {
	return isByte(elem) && !has(elem, "MarshalJSON") && !has(elem, "MarshalText") && !has(elem, "AppendText")
}

// maxKey is the longest key a Reader matches to a field, its keyBytes.
const maxKey = 256

func isTime(t types.Type) bool {
	n, ok := types.Unalias(t).(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == "time" && n.Obj().Name() == "Time"
}

func generic(n *types.Named) bool { return n.TypeParams().Len() > 0 || n.TypeArgs().Len() > 0 }

// addr is the address of the value at e, which for a dereference (*x) is x.
func addr(e string) string {
	if inner, ok := strings.CutPrefix(e, "(*"); ok && strings.HasSuffix(inner, ")") && !strings.Contains(inner, "(") {
		return strings.TrimSuffix(inner, ")")
	}
	return "&" + e
}

// keyLiteral is name as encoding/json writes it as a key, with its colon.
func keyLiteral(name string) string {
	b, _ := stdjson.Marshal(name)
	return string(b) + ":"
}

// writeMethod writes n's WriteJSON method.
func (g *gen) writeMethod(n *types.Named) {
	if generic(n) {
		g.fail("%s is generic; define an instance of it, such as type X %s[T], and generate that", n.Obj().Name(), n.Obj().Name())
		return
	}
	name := n.Obj().Name()
	g.p("\n// WriteJSON writes v as json.Marshal does.\n//\n//noalloc:root\nfunc (v *%s) WriteJSON(w *nojson.Writer) {", name)
	g.p("if !w.Enter(%q) { return }", name)
	if st, ok := n.Underlying().(*types.Struct); ok {
		g.writeStruct(st, "v", name)
	} else {
		g.writeValue(n.Underlying(), "(*v)", name, false)
	}
	g.p("w.Leave()")
	g.p("}")
}

// writeValue writes code that writes the value of type t at e.
func (g *gen) writeValue(t types.Type, e, field string, quoted bool) {
	if n, ok := types.Unalias(t).(*types.Named); ok {
		switch {
		case isTime(n):
			g.p("w.Time(%s, %q)", e, field)
			return
		case has(n, "WriteJSON"):
			g.p("%s.WriteJSON(w)", e)
			return
		case has(n, "MarshalJSON"):
			g.fail("%s: %s has MarshalJSON, whose result it allocates; give it a WriteJSON method", field, g.typ(n))
			return
		case has(n, "AppendText") && !has(n, "MarshalText"):
			g.fail("%s: %s has AppendText and no MarshalText; encoding/json writes it as text only with the jsonv2 experiment, so give it MarshalText too", field, g.typ(n))
			return
		case has(n, "AppendText"):
			b, err := g.v("b"), g.v("err")
			g.p("%s, %s := %s.AppendText(w.TextBegin())\nw.TextEnd(%s, %s, %q)", b, err, e, b, err, field)
			return
		case has(n, "MarshalText"):
			g.fail("%s: %s has MarshalText, whose result it allocates, and no AppendText", field, g.typ(n))
			return
		case generic(n):
			g.fail("%s: %s is generic; define an instance of it, such as type X %s, and use that", field, g.typ(n), g.typ(n))
			return
		}
		if _, ok := n.Underlying().(*types.Struct); ok {
			if n.Obj().Pkg() != g.pkg {
				g.fail("%s: %s is a struct of another package with no WriteJSON method; generate one there", field, g.typ(n))
				return
			}
			g.needWrite(n)
			g.p("%s.WriteJSON(w)", e)
			return
		}
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		g.writeBasic(u, e, field, quoted)
	case *types.Pointer:
		g.p("if %s == nil { w.Raw(\"null\") } else {", e)
		g.writeValue(u.Elem(), "(*"+e+")", field, quoted)
		g.p("}")
	case *types.Slice:
		if base64Slice(u.Elem()) {
			g.p("w.Base64(nojson.Bytes(%s))", e)
			return
		}
		i := g.v("i")
		g.p("if %s == nil { w.Raw(\"null\") } else {", e)
		g.writeRaw("[")
		g.p("for %s := range %s {\nif %s > 0 { w.Raw(\",\") }", i, e, i)
		g.writeValue(u.Elem(), e+"["+i+"]", field, false)
		g.p("}")
		g.writeRaw("]")
		g.p("}")
	case *types.Array:
		i := g.v("i")
		g.writeRaw("[")
		g.p("for %s := range %s {\nif %s > 0 { w.Raw(\",\") }", i, e, i)
		g.writeValue(u.Elem(), e+"["+i+"]", field, false)
		g.p("}")
		g.writeRaw("]")
	case *types.Struct:
		g.writeStruct(u, e, field)
	default:
		g.fail("%s: %s cannot be written without allocating", field, g.typ(t))
	}
}

func (g *gen) writeBasic(b *types.Basic, e, field string, quoted bool) {
	q := func(code string) {
		if quoted {
			g.writeRaw(`"`)
		}
		g.p("%s", code)
		if quoted {
			g.writeRaw(`"`)
		}
	}
	switch k := b.Kind(); {
	case k == types.Bool:
		q(fmt.Sprintf("w.Bool(bool(%s))", e))
	case k == types.Int || k == types.Int8 || k == types.Int16 || k == types.Int32 || k == types.Int64:
		q(fmt.Sprintf("w.Int(int64(%s))", e))
	case k == types.Uint || k == types.Uint8 || k == types.Uint16 || k == types.Uint32 || k == types.Uint64 || k == types.Uintptr:
		q(fmt.Sprintf("w.Uint(uint64(%s))", e))
	case k == types.Float32:
		q(fmt.Sprintf("w.Float(float64(%s), 32, %q)", e, field))
	case k == types.Float64:
		q(fmt.Sprintf("w.Float(float64(%s), 64, %q)", e, field))
	case k == types.String:
		if quoted {
			g.p("w.QuotedString(string(%s))", e)
		} else {
			g.p("w.String(string(%s))", e)
		}
	default:
		g.fail("%s: %s cannot be written as JSON", field, b)
	}
}

// writeStruct writes code that writes the struct at e as an object.
func (g *gen) writeStruct(st *types.Struct, e, typeName string) {
	fields := fieldsOf(st)
	g.writeRaw("{")
	// wrote is whether a field is certain to have been written, so the next
	// needs a comma. Until one is, more holds at run time whether a field
	// that may be left out was written.
	wrote, more := false, ""
	comma := func() {
		switch {
		case wrote:
			g.writeRaw(",")
		case more != "":
			g.p("if %s { w.Raw(\",\") }", more)
		}
	}
	for _, f := range fields {
		sel, conds := selector(e, f)
		skip := g.skipExpr(f, sel)
		field := typeName + "." + f.goName
		parts := slices.Clone(conds)
		if skip != "" {
			parts = append(parts, "!("+skip+")")
		}
		if len(parts) > 0 {
			if !wrote && more == "" {
				more = g.v("more")
				g.p("%s := false", more)
			}
			g.p("if %s {", strings.Join(parts, " && "))
			comma()
			g.writeRaw(keyLiteral(f.name))
			g.writeValue(f.typ, sel, field, f.quoted)
			if !wrote {
				g.p("%s = true", more)
			}
			g.p("}")
			continue
		}
		comma()
		g.writeRaw(keyLiteral(f.name))
		g.writeValue(f.typ, sel, field, f.quoted)
		wrote = true
	}
	g.writeRaw("}")
}

// selector is the expression for f in the struct at e, and the conditions
// for reaching it through embedded pointers.
func selector(e string, f field) (string, []string) {
	var conds []string
	cur := e
	for i, step := range f.path {
		cur += "." + step.Name()
		if i < len(f.path)-1 {
			if _, ok := step.Type().(*types.Pointer); ok {
				conds = append(conds, cur+" != nil")
			}
		}
	}
	return cur, conds
}

// skipExpr is when a field tagged omitempty or omitzero is left out, or "".
func (g *gen) skipExpr(f field, e string) string {
	var parts []string
	if f.omitEmpty {
		if s := emptyExpr(f.typ, e); s != "" {
			parts = append(parts, s)
		}
	}
	if f.omitZero {
		parts = append(parts, g.zeroExpr(f.typ, e, f.goName))
	}
	return strings.Join(parts, " || ")
}

// emptyExpr is encoding/json's omitempty test for the value of t at e, or ""
// for a type no value of which is empty.
func emptyExpr(t types.Type, e string) string {
	switch u := t.Underlying().(type) {
	case *types.Array:
		if u.Len() == 0 {
			return "true"
		}
	case *types.Slice, *types.Map:
		return "len(" + e + ") == 0"
	case *types.Pointer, *types.Interface:
		return e + " == nil"
	case *types.Basic:
		switch {
		case u.Info()&types.IsBoolean != 0:
			return "!bool(" + e + ")"
		case u.Info()&types.IsString != 0:
			return "len(" + e + ") == 0"
		case u.Info()&types.IsNumeric != 0:
			return e + " == 0"
		}
	}
	return ""
}

// zeroExpr is encoding/json's omitzero test for the value of t at e: its
// IsZero method, or whether every bit of it is zero.
func (g *gen) zeroExpr(t types.Type, e, field string) string {
	if has(t, "IsZero") {
		if _, ok := t.Underlying().(*types.Pointer); ok {
			return "(" + e + " == nil || " + e + ".IsZero())"
		}
		return e + ".IsZero()"
	}
	return g.bitsZero(t, e, field)
}

// bitsZero is whether every bit of the value of t at e is zero, as
// reflect.Value.IsZero has it.
func (g *gen) bitsZero(t types.Type, e, field string) string {
	switch u := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case u.Kind() == types.Float32:
			g.importName("math", "math")
			return "math.Float32bits(float32(" + e + ")) == 0"
		case u.Kind() == types.Float64:
			g.importName("math", "math")
			return "math.Float64bits(float64(" + e + ")) == 0"
		case u.Info()&types.IsBoolean != 0:
			return "!bool(" + e + ")"
		case u.Info()&types.IsString != 0:
			return "len(" + e + ") == 0"
		default:
			return e + " == 0"
		}
	case *types.Pointer, *types.Slice, *types.Map, *types.Interface, *types.Chan, *types.Signature:
		return e + " == nil"
	}
	// == agrees with the bits wherever no float is involved, and reaches
	// fields of other packages' structs that this package cannot name.
	if types.Comparable(t) && !holdsFloat(t, map[types.Type]bool{}) {
		return e + " == (" + g.typ(t) + "{})"
	}
	switch u := t.Underlying().(type) {
	case *types.Array:
		i := g.v("i")
		return "func() bool { for " + i + " := range " + e + " { if !(" + g.bitsZero(u.Elem(), e+"["+i+"]", field) +
			") { return false } }; return true }()"
	case *types.Struct:
		var parts []string
		for i := range u.NumFields() {
			f := u.Field(i)
			if !f.Exported() && f.Pkg() != g.pkg {
				g.fail("%s: omitzero needs %s's unexported fields, which this package cannot read", field, g.typ(t))
				return "false"
			}
			if f.Name() == "_" {
				continue
			}
			parts = append(parts, g.bitsZero(f.Type(), e+"."+f.Name(), field))
		}
		if len(parts) == 0 {
			return "true"
		}
		return "(" + strings.Join(parts, " && ") + ")"
	}
	g.fail("%s: no omitzero test for %s", field, g.typ(t))
	return "false"
}

// holdsFloat reports whether a value of t holds a float in place, where ==
// and a bit comparison differ.
func holdsFloat(t types.Type, seen map[types.Type]bool) bool {
	if seen[t] {
		return false
	}
	seen[t] = true
	switch u := t.Underlying().(type) {
	case *types.Basic:
		return u.Info()&(types.IsFloat|types.IsComplex) != 0
	case *types.Array:
		return holdsFloat(u.Elem(), seen)
	case *types.Struct:
		for i := range u.NumFields() {
			if holdsFloat(u.Field(i).Type(), seen) {
				return true
			}
		}
	}
	return false
}

// readMethod writes n's ReadJSON method.
func (g *gen) readMethod(n *types.Named) {
	if generic(n) {
		g.fail("%s is generic; define an instance of it, such as type X %s[T], and generate that", n.Obj().Name(), n.Obj().Name())
		return
	}
	name := n.Obj().Name()
	g.p("\n// ReadJSON reads v as json.Unmarshal does.\n//\n//noalloc:root\nfunc (v *%s) ReadJSON(r *nojson.Reader) {", name)
	if st, ok := n.Underlying().(*types.Struct); ok {
		g.readStruct(st, "v", name)
	} else {
		g.readValue(n.Underlying(), "(*v)", name)
	}
	g.p("}")
}

// readValue writes code that reads a value of type t into e, addressable.
func (g *gen) readValue(t types.Type, e, field string) {
	if n, ok := types.Unalias(t).(*types.Named); ok {
		switch {
		case isTime(n):
			g.p("r.Time(%s, %q)", addr(e), field)
			return
		case has(n, "ReadJSON"):
			g.p("%s.ReadJSON(r)", e)
			return
		case has(n, "UnmarshalJSON"):
			g.fail("%s: %s has UnmarshalJSON, which reads from memory it is handed whole; give it a ReadJSON method", field, g.typ(n))
			return
		case has(n, "UnmarshalText"):
			b, ok := g.v("b"), g.v("ok")
			g.p("if %s, %s := r.Text(%q); %s { r.TextErr(%s.UnmarshalText(%s), %q) }", b, ok, field, ok, e, b, field)
			return
		case generic(n):
			g.fail("%s: %s is generic; define an instance of it, such as type X %s, and use that", field, g.typ(n), g.typ(n))
			return
		}
		if _, ok := n.Underlying().(*types.Struct); ok {
			if n.Obj().Pkg() != g.pkg {
				g.fail("%s: %s is a struct of another package with no ReadJSON method; generate one there", field, g.typ(n))
				return
			}
			g.needRead(n)
			g.p("%s.ReadJSON(r)", e)
			return
		}
	}
	switch u := t.Underlying().(type) {
	case *types.Basic:
		g.readBasic(t, u, e, field)
	case *types.Pointer:
		g.p("if r.Null() { %s = nil } else if %s == nil { r.Full(%q); r.Skip() } else {", e, e, field)
		g.readValue(u.Elem(), "(*"+e+")", field)
		g.p("}")
	case *types.Slice:
		if isByte(u.Elem()) {
			g.fail("%s: reading a slice of bytes, which encoding/json reads from base64, is not supported", field)
			return
		}
		s := g.v("s")
		g.p("if r.Null() { %s = nil } else if r.ArrayStart(%q) {\n%s := %s[:0]", e, field, s, e)
		g.p("if %s == nil { %s = nojson.Empty[%s]() }", s, s, g.typ(u.Elem()))
		g.p("for r.ArrayNext() {\nif len(%s) == cap(%s) { r.Full(%q); r.Skip(); continue }", s, s, field)
		// The element is decoded into as it was, as encoding/json decodes
		// into a slice's memory, so slices it holds keep their room.
		g.p("%s = %s[:len(%s)+1]", s, s, s)
		g.readValue(u.Elem(), s+"[len("+s+")-1]", field)
		g.p("}\n%s = %s\n}", e, s)
	case *types.Array:
		i := g.v("i")
		g.p("if r.ArrayStart(%q) {\n%s := 0\nfor r.ArrayNext() {\nif %s < len(%s) {", field, i, i, e)
		g.readValue(u.Elem(), e+"["+i+"]", field)
		g.p("} else { r.Skip() }\n%s++\n}", i)
		z := g.v("zero")
		g.p("var %s %s\nfor ; %s < len(%s); %s++ { %s[%s] = %s }\n}", z, g.typ(u.Elem()), i, e, i, e, i, z)
	case *types.Struct:
		g.readStruct(u, e, field)
	default:
		g.fail("%s: %s cannot be read without allocating", field, g.typ(t))
	}
}

func (g *gen) readBasic(t types.Type, b *types.Basic, e, field string) {
	conv := g.typ(t)
	x, ok := g.v("x"), g.v("ok")
	bits := map[types.BasicKind]string{types.Int: "nojson.IntBits", types.Int8: "8", types.Int16: "16", types.Int32: "32",
		types.Int64: "64", types.Uint: "nojson.IntBits", types.Uint8: "8", types.Uint16: "16", types.Uint32: "32",
		types.Uint64: "64", types.Uintptr: "nojson.IntBits", types.Float32: "32", types.Float64: "64"}
	switch k := b.Kind(); {
	case k == types.Bool:
		g.p("if %s, %s := r.Bool(%q); %s { %s = %s(%s) }", x, ok, field, ok, e, conv, x)
	case k == types.Int || k == types.Int8 || k == types.Int16 || k == types.Int32 || k == types.Int64:
		g.p("if %s, %s := r.Int(%q, %s); %s { %s = %s(%s) }", x, ok, field, bits[k], ok, e, conv, x)
	case k == types.Uint || k == types.Uint8 || k == types.Uint16 || k == types.Uint32 || k == types.Uint64 || k == types.Uintptr:
		g.p("if %s, %s := r.Uint(%q, %s); %s { %s = %s(%s) }", x, ok, field, bits[k], ok, e, conv, x)
	case k == types.Float32 || k == types.Float64:
		g.p("if %s, %s := r.Float(%q, %s); %s { %s = %s(%s) }", x, ok, field, bits[k], ok, e, conv, x)
	case k == types.String:
		g.p("r.String((*string)(%s), %q)", addr(e), field)
	default:
		g.fail("%s: %s cannot be read from JSON", field, b)
	}
}

// readStruct writes code that reads an object into the struct at e.
func (g *gen) readStruct(st *types.Struct, e, typeName string) {
	fields := fieldsOf(st)
	for _, f := range fields {
		if len(f.name) > maxKey {
			g.fail("%s.%s: a key longer than %d bytes cannot be matched", typeName, f.goName, maxKey)
		}
	}
	g.p("if r.ObjectStart(%q) {\nfor r.ObjectNext() {", typeName)
	if len(fields) == 0 {
		g.p("r.Skip()\n}\n}")
		return
	}
	k, f := g.v("k"), g.v("f")
	g.p("%s := r.Key()\n%s := -1\nswitch %s {", k, f, k)
	for i, fl := range fields {
		g.p("case %q: %s = %d", fl.name, f, i)
	}
	g.p("default:\nswitch {")
	for i, fl := range fields {
		g.p("case nojson.KeyFold(%s, %q): %s = %d", k, fl.name, f, i)
	}
	g.p("}\n}\nswitch %s {", f)
	for i, fl := range fields {
		field := typeName + "." + fl.goName
		if fl.quoted {
			g.fail("%s: reading a \",string\" field is not supported", field)
			continue
		}
		sel, conds := selector(e, fl)
		if len(conds) > 0 {
			g.fail("%s: reading a field through an embedded pointer is not supported", field)
			continue
		}
		g.p("case %d:", i)
		g.readValue(fl.typ, sel, field)
	}
	g.p("default:\nr.Skip()\n}\n}\n}")
}
